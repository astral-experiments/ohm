"""Verify both original inode ledgers, clean payload identities, and the unmetered decision."""
import hashlib
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent

def digest(data):
    return hashlib.sha256(data).hexdigest()

def main():
    q=json.loads((HERE/"summary.json").read_bytes())
    assert q["run"]==41440080008 and q["factory"]==41431225435 and not q["hardware_counters_collected"]
    assert q["artifact"]=={"id":13140400786,"name":"ruff-29206-ordinary-objects","bytes":179296595,
                           "digest":"sha256:b9f909108cf56a78394ff5f653d2b0eb1dc31741ff8f2b76211829dec4730ad5"}
    assert (q["registry"]["products"],q["registry"]["shared"],q["validation"]["units"])==(195,162,271)
    by_role={}
    for role in "PC":
        data=(HERE/f"objects-{role}.json").read_bytes();ledgers=json.loads(data);by_role[role]={}
        for owner,o in ledgers.items():
            assert digest(data)==q["histories"][role]["owners"][owner]["source_ledger_sha256"]
            entries=o["objects"];by_role[role][owner]=entries
            for label,which in (("old","before"),("new","after")):
                raw={name:[x[which+"_sha256"],x[which][2]] for name,x in entries.items() if x[which]}
                stable=digest(json.dumps(raw,sort_keys=True,separators=(",",":")).encode())
                reference=q["clean_native"][role+"-"+label][owner]
                assert len(raw)==reference["native_cgus"] and stable==reference["stable_cgu_sha256"]
            for x in entries.values():
                a,b=x["before"],x["after"];retained=bool(a and b and a[:2]==b[:2])
                assert x["retained"] is retained and (not retained or (a[2]==b[2] and x["before_sha256"]==x["after_sha256"]))
    for owner in ("ruff_linter","ruff_python_literal"):
        p,c=[by_role[r][owner] for r in "PC"];assert set(p)==set(c)
        gained=sorted(k for k in p if not p[k]["retained"] and c[k]["retained"])
        lost=sorted(k for k in p if p[k]["retained"] and not c[k]["retained"])
        red=sum(x["after"][2] for x in p.values() if x["after"] and not x["retained"])
        net=sum(p[k]["after"][2] for k in gained)-sum(p[k]["after"][2] for k in lost)
        expected=q["screen"]["owners"][owner]
        assert (gained,lost,red,net)==(expected["gained"],expected["lost"],expected["parent_regenerated_bytes"],expected["net_extra_donor_bytes"])
        assert (sum(v["retained"] for v in p.values()),sum(v["retained"] for v in c.values()))==(expected["parent"],expected["candidate"])
        if owner=="ruff_linter":
            assert q["screen"]["minimum_net_share"]=="1/10" and q["screen"]["meaningful"]==(10*net>=red)==False
            assert sum(x["before_sha256"]!=x["after_sha256"] for x in p.values())==14
        print(f"{owner}: {expected['parent']} to {expected['candidate']} donors; {net:,}/{red:,} regenerated bytes recovered.")
    source=q["typed"];assert {k for k,v in source["old"].items() if source["new"][k]!=v}=={"mixed","blank"}
    assert all(v.startswith("F401=1 used=0 invalid=1\n") for values in source.values() for v in values.values())
    assert q["validation"]["typed_executions"]==50 and q["validation"]["independent_clean_comparisons"]==12
    print("The linter recovered 2.870336% against the registered 10% native-byte threshold.")

if __name__=="__main__":main()
